import { readFile, writeFile } from 'node:fs/promises';
import { iconNodes } from '../desktop/src/shared/components/lucide-icons.js';
import { iconMarkup } from '../desktop/src/shared/components/icons.js';

// One geometry source for dynamic DOM icons and static, same-origin SVG use.
const output = new URL('../desktop/design-previews/components/icons.svg', import.meta.url);
const symbols = Object.keys(iconNodes).map(name => iconMarkup(name)
  .replace(/^<svg[^>]+>/, `  <symbol id="${name}" viewBox="0 0 24 24">`)
  .replace('</svg>', '</symbol>')).join('\n');
const sprite = `<!-- Generated by scripts/build-preview-icons.mjs. See LUCIDE-SOURCE.md and LUCIDE-LICENSE. -->\n<svg xmlns="http://www.w3.org/2000/svg">\n${symbols}\n</svg>\n`;

if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== sprite) throw new Error('Preview icon sprite is stale. Run node scripts/build-preview-icons.mjs.');
  console.log(`Preview icon sprite is current (${Object.keys(iconNodes).length} symbols).`);
} else {
  await writeFile(output, sprite);
  console.log(`Generated ${Object.keys(iconNodes).length} preview icon symbols.`);
}
